// Building and placing the generated "What's new" card grid in a docs article.
//
// Pure functions, no I/O, so the tests can exercise them without a repository.
// Used by apply-release-links.mjs.
//
// Everything the automation writes lives between the two markers. Strip that
// region from a file before and after an edit and the two must be identical —
// `applyBlock` checks exactly that and throws rather than write. It is the
// only reason automation is allowed near docs/ at all.
//
// The block sits at the END of the article, below "Related articles", and
// matches that section's markup: a <CardGroup cols={2}> of <Card> elements
// with an icon, a title and a sentence of description.

export const END = "{/* release-notes:end */}";

/**
 * The opening marker carries the release labels it covers.
 *
 * They are recorded here rather than parsed back out of the rendered cards:
 * reading them from prose means every change to how a card looks risks
 * breaking the "have we already added this?" check, and an article that
 * cannot recognise its own block is rewritten on every single run.
 */
export const startMarker = (labels = []) =>
  `{/* release-notes:start ${labels.join(",")} — generated by scripts/apply-release-links.mjs, do not edit by hand */}`;

export const BLOCK_RE =
  /\n*\{\/\* release-notes:start[\s\S]*?release-notes:end \*\/\}\n?/;

/** The file with any generated block removed — what must never change. */
export function withoutBlock(text) {
  return text.replace(BLOCK_RE, "\n").replace(/\n{3,}/g, "\n\n");
}

/** Release labels this article's block already covers. */
export function labelsInArticle(text) {
  const m = text.match(/\{\/\* release-notes:start ([^—]*)—/);
  if (!m) return [];
  return m[1]
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
}

/** Mintlify builds a heading anchor from the heading text. */
export const anchorFor = (heading) =>
  String(heading)
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");

/**
 * Which week a label means — the convention changed, so it cannot be assumed.
 *
 * The 2021 year file labels releases year-first (WK21-46 is 2021, week 46).
 * By 2025 it is week-first (WK48-25 is week 48 of 2025). Reading either as the
 * other puts WK21-46 in 2046 and sorts a 2021 release above a 2026 one.
 *
 * The year file the block lives in is authoritative, so the component matching
 * the year is the year and the other is the week. As a side effect this reads
 * the transposed WK26-40 correctly as week 40 of 2026.
 */
export function weekOf(label, year) {
  const m = String(label).match(/^WK(\d{1,2})-(\d{1,2})$/i);
  if (!m) return 0;
  const [a, b] = [Number(m[1]), Number(m[2])];
  const yy = Number(year) % 100;
  if (b === yy) return a;
  if (a === yy) return b;
  return a;
}

/** Escape the characters MDX treats as syntax, leaving inline code alone. */
function escapeMdx(text) {
  const code = [];
  let out = String(text).replace(/`[^`\n]*`/g, (m) => {
    code.push(m);
    return `@@C${code.length - 1}@@`;
  });
  out = out.replace(/</g, "&lt;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;");
  return out.replace(/@@C(\d+)@@/g, (_, i) => code[Number(i)]);
}

/**
 * One sentence of description from the release note's prose.
 *
 * The note's own words, not a paraphrase — these are written by the person who
 * shipped the feature and say what actually changed, which is the whole point
 * of putting them on the article.
 */
export function summarize(body, max = 180) {
  let text = String(body || "")
    .replace(/<Frame>[\s\S]*?<\/Frame>/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/^\s*\d+\.\s+/gm, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!text) return "";

  // Prefer a whole sentence; fall back to a word boundary.
  if (text.length > max) {
    const cut = text.slice(0, max);
    const stop = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("! "));
    text = stop > max * 0.4 ? cut.slice(0, stop + 1) : cut.replace(/\s+\S*$/, "") + "…";
  } else {
    const stop = text.indexOf(". ");
    if (stop > 40) text = text.slice(0, stop + 1);
  }
  return escapeMdx(text.trim());
}

/**
 * The card grid, matching the "Related articles" section's markup.
 *
 * Each card links to that feature's own heading in the year file. The link
 * lands on the right page even when the anchor is wrong, so a change in how
 * Mintlify slugs headings degrades to "right page, top of page" rather than
 * to a broken link.
 */
export function renderCards(entries) {
  const lines = [
    startMarker(entries.map((e) => e.label)),
    "",
    "## What's new",
    "",
    entries.length === 1
      ? "One release has changed this feature since the article was written."
      : `${entries.length} releases have changed this feature since the article was written.`,
    "",
    "<CardGroup cols={2}>",
  ];

  // Entries arrive newest first, so the first card is the most recent change
  // to this feature and carries the Latest badge. <Badge> is already used in
  // the repo with these props, so this is house style rather than an invention.
  entries.forEach((e, i) => {
    const href = `/blog/releases/${e.year}#${anchorFor(e.heading)}`;
    const title = escapeMdx(e.heading);
    const meta = [e.label, e.date].filter(Boolean).join(" · ");
    const summary = summarize(e.body);
    const badge = i === 0 ? '<Badge color="purple" size="sm">Latest</Badge> ' : "";
    lines.push(`  <Card title="${title.replace(/"/g, "&quot;")}" icon="rocket" href="${href}">`);
    lines.push(`    ${badge}**${meta}**${summary ? ` — ${summary}` : ""}`);
    lines.push("  </Card>");
  });

  lines.push("</CardGroup>", "", END);
  return lines.join("\n");
}

/**
 * Insert or replace the block at the END of the article. Returns the new text,
 * or throws if anything outside the block would change.
 */
export function applyBlock(original, cards) {
  const eol = original.includes("\r\n") ? "\r\n" : "\n";
  const text = original.replace(/\r\n/g, "\n");

  if (!/^---\n[\s\S]*?\n---\n/.test(text)) {
    throw new Error("no frontmatter — refusing to edit a file that is not an article");
  }

  // Strip any existing block wherever it is, then append. Replacing in place
  // would leave the earlier top-of-page blocks at the top forever, and the
  // block is meant to sit below "Related articles".
  const stripped = withoutBlock(text).replace(/\s*$/, "");
  const next = `${stripped}\n\n${cards}\n`;

  // THE GUARD. With strip-then-append the two sides agree by construction for
  // a well-formed block, so what this actually catches is a malformed one: a
  // `cards` string carrying an early end marker closes the region too soon and
  // leaves its tail outside, which is the shape a corrupting edit takes. The
  // test suite sabotages exactly that.
  if (withoutBlock(text).trim() !== withoutBlock(next).trim()) {
    throw new Error(
      "the edit would have changed text outside the generated block. Nothing written."
    );
  }

  return next.replace(/\n/g, eol);
}
